#include <stddef.h>
#include <stdio.h>

size_t	ft_strlcpy(char *dst, const char *src, size_t size)
{
	size_t	i;
	size_t	j;

	i = 0;
	j = 0;
	while (src[j])
		j++;
	while (src[i] && i < size - 1)
	{
		dst[i] = src[i];
		i++;
	}
	dst[i] = '\0';
	return (j);
}

int main ()
{
	char s[] = "hello";
	char d[] = "h";
	printf("%zu\n", ft_strlcpy(d, s, 3));
	printf("%s",d);
}
